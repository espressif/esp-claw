local audio, delay = require("audio"), require("delay")
local output = assert(audio.open_output())
local volume = output:get_volume()
assert(output:set_volume(0))

local function new_sample_player(rate)
    return assert(audio.sample_player({ output = output, source_rate = rate, max_voices = 6, attack_ms = 4, release_ms = 15 }))
end

-- A failed/unstarted holder must not release another sample_player's output.
for _, rate in ipairs({ 8000, 16000, 44100, 48000 }) do
    local sample_player = new_sample_player(rate)
    assert(not sample_player:start())
    assert(not sample_player:load(1, "x"))
    assert(sample_player:load(1, string.rep("\0\0", rate)))
    assert(sample_player:load(2, "\0\0"))
    assert(not sample_player:load(1, "\0\0"))
    assert(not sample_player:trigger(1))
    assert(sample_player:start())
    assert(not sample_player:start())
    assert(not sample_player:load(2, "\0\0"))
    assert(not sample_player:trigger(99))
    assert(not sample_player:trigger(1, -1))
    assert(not sample_player:trigger(1, 0 / 0))
    for i = 1, 6 do assert(sample_player:trigger(1, 0.5, i * 2)) end
    local other = new_sample_player(rate)
    assert(other:load(1, "\0\0"))
    assert(not other:start())
    assert(other:close())
    assert(not output:write("\0\0"))
    assert(not output:close())
    delay.delay_ms(100)
    if rate == 16000 then
        local rejected = 0
        for i = 1, 256 do
            local ok, err = sample_player:trigger(1, 0.5)
            if not ok then assert(err:find("ESP_ERR_TIMEOUT", 1, true)); rejected = rejected + 1 end
        end
        assert(rejected > 0, "queue saturation was not exercised")
    end
    local before = output:status()
    delay.delay_ms(500)
    local status, track = sample_player:status(), output:status()
    assert(status.error == "ESP_OK", status.error)
    assert(status.rendered_blocks > 10)
    assert(track.missing_frames == before.missing_frames, "PCM underrun")
    assert(track.queued_ms <= 45, "excessive buffering")
    print(string.format("SAMPLE PLAYER PASS rate=%d render_max_us=%.0f queued_ms=%.1f", rate, status.render_max_us, track.queued_ms))
    assert(sample_player:clear())
    assert(sample_player:trigger(1, 0.5, 0, 40))
    delay.delay_ms(150)
    assert(sample_player:status().active_voices == 0, "duration ignored")
    assert(sample_player:trigger(1, 0.5, 700, 100))
    assert(sample_player:clear())
    assert(sample_player:trigger(1, 0.5, 0, 300))
    delay.delay_ms(100)
    assert(sample_player:status().active_voices == 1, "clear lost following note")
    delay.delay_ms(750)
    assert(sample_player:status().active_voices == 0, "clear retained pending note")
    assert(not pcall(sample_player.trigger, sample_player, 1, 1, 0, -1))
    assert(not pcall(sample_player.trigger, sample_player, 1, 1, 0, 60001))
    for _, speed in ipairs({0, 0.24, 4.01, math.huge, 0 / 0}) do
        assert(not sample_player:trigger(1, 1, 0, 0, speed), "invalid rate accepted")
    end
    assert(sample_player:trigger(1, 1, 0, 0, 4))
    delay.delay_ms(350)
    assert(sample_player:status().active_voices == 0, "fast sample retained original duration")
    assert(sample_player:trigger(1, 1, 0, 0, 0.25))
    delay.delay_ms(1100)
    assert(sample_player:status().active_voices == 1, "slow sample ended too early")
    assert(sample_player:clear())
    assert(sample_player:trigger(1, 1, 0, 40, 0.25))
    assert(sample_player:trigger(2, 1, 0, 0, 0.25))
    delay.delay_ms(150)
    assert(sample_player:status().active_voices == 0, "rate changed explicit duration")
    assert(sample_player:close())
    assert(sample_player:close())
    assert(output:write("\0\0") == 2)
end

-- Budget failures leave loaded samples and accounting intact.
local bounded = assert(audio.sample_player({output = output, sample_budget_bytes = 8, max_voices = 1}))
assert(bounded:status().sample_bytes == 0)
assert(bounded:load(1, string.rep("\0", 6)))
assert(not bounded:load(2, string.rep("\0", 4)))
assert(bounded:status().loaded_samples == 1 and bounded:status().sample_bytes == 6)
assert(bounded:load(2, "\0\0"))
assert(bounded:status().sample_bytes == 8 and bounded:status().sample_budget_bytes == 8)
assert(not bounded:load(3, "\0\0"))
assert(bounded:close())
assert(not pcall(audio.sample_player, {output = output, sample_budget_bytes = 1}))

-- Playback handles survive slot reuse without targeting the replacement.
local voices = assert(audio.sample_player({output = output, max_voices = 2}))
assert(voices:load(1, string.rep("\0\0", 16000 * 3)))
assert(voices:start())
local first = assert(voices:trigger(1))
local second = assert(voices:trigger(1))
assert(type(first) == "userdata" and first ~= second)
delay.delay_ms(100)
assert(voices:status().active_voices == 2)
assert(voices:stop(first))
delay.delay_ms(100)
assert(voices:status().active_voices == 1, "stop affected unrelated voice")
assert(voices:stop(first))
local replacement = assert(voices:trigger(1))
local newest = assert(voices:trigger(1))
assert(voices:stop(second))
delay.delay_ms(100)
assert(voices:status().active_voices == 2, "stale handle stopped stolen slot")
assert(voices:clear())
local pending = assert(voices:trigger(1, 1, 500))
assert(voices:stop(pending))
delay.delay_ms(650)
assert(voices:status().active_voices == 0, "pending voice not cancelled")
local expired = assert(voices:trigger(1, 1, 0, 40))
delay.delay_ms(150)
assert(voices:status().active_voices == 0)
local survivor = assert(voices:trigger(1))
assert(voices:stop(expired))
assert(voices:stop(replacement) and voices:stop(newest))
delay.delay_ms(100)
assert(voices:status().active_voices == 1, "clear reused handle IDs")
local other = new_sample_player(16000)
assert(other:load(1, "\0\0"))
assert(not other:start(), "output must remain exclusive")
assert(not pcall(other.stop, other, survivor), "foreign handle accepted")
assert(other:close())
local file_player = assert(audio.player({output = output}))
assert(not file_player:play("missing.aac"), "file player acquired busy output")
assert(file_player:close())
assert(not output:write("\0\0"), "failed player released another owner")
assert(voices:stop(survivor))
delay.delay_ms(100)
assert(voices:status().active_voices == 0)
assert(voices:close())
assert(file_player:close())
assert(not pcall(voices.stop, voices, survivor))
first, second, replacement, newest, pending, survivor, expired = nil, nil, nil, nil, nil, nil, nil
collectgarbage("collect")
print("SAMPLE PLAYER PASS handles, budget, exclusive output")

-- Finalization must join the worker before releasing the output or PCM.
for i = 1, 3 do
    local sample_player = new_sample_player(16000)
    assert(sample_player:load(1, string.rep("\0\0", 16000)))
    assert(sample_player:start())
    assert(sample_player:trigger(1))
    sample_player = nil
    collectgarbage("collect")
    assert(output:write("\0\0") == 2)
end
assert(output:set_volume(volume))
assert(output:close())
print("SAMPLE PLAYER PASS lifecycle")
