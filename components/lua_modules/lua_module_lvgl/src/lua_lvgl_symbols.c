#define LUA_LVGL_SYMBOL_COUNT \
    (sizeof(s_symbols) / sizeof(s_symbols[0]))

void lua_lvgl_push_symbol_table(lua_State *L)
{
    lua_createtable(L, 0, (int)LUA_LVGL_SYMBOL_COUNT);
    for (size_t i = 0; i < LUA_LVGL_SYMBOL_COUNT; i++) {
        lua_pushstring(L, s_symbols[i].utf8);
        lua_setfield(L, -2, s_symbols[i].name);
    }
}
