local display = require("display")
local delay = require("delay")
local function fails(fn)
    assert(not pcall(fn), "expected display error")
end
fails(function() display.open({framebuffer_count = 3}) end)
for count = 1, 2 do
    local screen <close> = display.open({framebuffer_count = count})
    local info = screen:info()
    assert(info.pixel_format == "rgb565" and info.bytes_per_pixel == 2)
    assert(info.framebuffer_bytes == info.width * info.height * 2 * count)
    fails(function() display.open() end)
    fails(function() screen:present() end)
    fails(function() screen:fill_rect(0, 0, 4, 4, "#ffffff") end)
    screen:begin({clear = "#000000"})
    fails(function() screen:begin() end)
    screen:fill_rect(0, 0, 10, 10, "#ff0000")
    screen:fill_rect(10, 0, 10, 10, display.color(0, 255, 0))
    screen:fill_rect(20, 0, 10, 10, {0, 0, 255})
    screen:save()
    screen:translate(10, 20)
    screen:clip(0, 0, 3, 3)
    screen:fill_rect(-5, -5, 20, 20, "#ffffff")
    screen:restore()
    local w, h = screen:measure_text("TEST", {font_size = 24})
    assert(w > 0 and h > 0)
    screen:text(40, 40, "TEST", {font_size = 24})
    assert(screen:present())
    delay.delay_ms(30)
    -- Partial updates must retain both the source stride and previous pixels.
    screen:begin()
    screen:fill_rect(60, 10, 3, 5, "#ffffff")
    assert(screen:present())
    delay.delay_ms(30)
    screen:begin()
    assert(not screen:present())
    fails(function() screen:image(0, 0, {}) end)
    assert(type(screen:touch().points) == "table")
    screen:close()
    screen:close()
    fails(function() screen:info() end)
end
-- Runtime cleanup owns resources even when Lua drops all references.
display.open()
print("DISPLAY_CONTRACT_OK")
